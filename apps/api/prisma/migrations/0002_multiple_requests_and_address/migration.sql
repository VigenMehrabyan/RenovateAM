-- RenovateAM — несколько заявок на клиента и адрес объекта в заявке.
--
-- Идёт на базу, где заявки уже есть, поэтому каждый шаг написан так, чтобы
-- повторный запуск не ломался (`IF EXISTS` / `IF NOT EXISTS`), а существующие
-- строки получили значения до включения NOT NULL.

-- --------------------------------------------------------------------------
-- 1. Снятие инварианта «одна активная заявка на клиента»
-- --------------------------------------------------------------------------
-- Заказчик разрешил вести несколько заявок одновременно. Защиту от случайного
-- дубля (двойное нажатие) индекс больше не даёт — её берёт на себя окно
-- «не более трёх заявок в час», см. RequestsRepository.createWithLogWithinLimit:
-- счётчик и вставка идут одной транзакцией под advisory-блокировкой
-- по пользователю, поэтому параллельные отправки не обходят лимит.
DROP INDEX IF EXISTS "requests_one_active_per_user";

-- --------------------------------------------------------------------------
-- 2. Адрес объекта переезжает из профиля в заявку
-- --------------------------------------------------------------------------
-- users.address остаётся контактным адресом пользователя и не удаляется.
-- Для уже созданных заявок объектом считается адрес из профиля владельца —
-- единственный адрес, который на момент их создания существовал.
ALTER TABLE "requests" ADD COLUMN IF NOT EXISTS "address" VARCHAR(500);

UPDATE "requests" AS r
   SET "address" = u."address"
  FROM "users" AS u
 WHERE u."id" = r."user_id"
   AND r."address" IS NULL;

ALTER TABLE "requests" ALTER COLUMN "address" SET NOT NULL;

-- --------------------------------------------------------------------------
-- 3. Индексы под кабинет клиента
-- --------------------------------------------------------------------------
-- Список кабинета сортируется по дате последнего изменения; окно антидубля
-- считает заявки пользователя за последний час — обоим нужен (user_id, ...).
CREATE INDEX IF NOT EXISTS "requests_user_id_updated_at_idx"
    ON "requests" ("user_id", "updated_at");
