/**
 * Типы базы знаний чат-бота.
 *
 * Этот файл — общий словарь двух команд: он описывает ФОРМАТ данных и ничего
 * не знает ни о Nest, ни о Prisma, ни о HTTP. Движок поиска (`search/`) и
 * сами данные (`entries.ts`) зависят от него, а не друг от друга.
 */

/** Кнопка под ответом бота. Подпись и ссылку рисует фронтенд по этому значению. */
export type ChatActionKind =
  /** «Посчитать цену» — ведёт на калькулятор на главной. */
  | 'ESTIMATE'
  /** «Оставить заявку» — ведёт на форму заявки. */
  | 'REQUEST'
  /** «Посмотреть работы» — внешняя ссылка на Instagram, новая вкладка. */
  | 'PORTFOLIO'
  /** «Позвонить» — tel:-ссылка. */
  | 'CALL'
  /** «Позвать человека» — POST /chat/sessions/:id/handoff. */
  | 'HUMAN';

/** Строка на трёх языках. Пустых значений быть не должно. */
export interface Localized {
  ru: string;
  hy: string;
  en: string;
}

/**
 * Ключевые слова по раскладкам. `hyLatin` — армянский язык, записанный
 * латиницей («inch arji», «qarakusi metr»): по нему же определяется язык
 * сообщения, поэтому держим его отдельным списком, а не вперемешку с `en`.
 */
export interface ChatKeywords {
  ru: string[];
  hy: string[];
  hyLatin: string[];
  en: string[];
}

export interface ChatEntry {
  /** Стабильный id темы. Уходит в аналитику и в `chat_messages.entry_id` — не переименовывать. */
  id: string;
  /** Тема для админки и логов, по-русски. Посетителю не показывается. */
  topic: string;
  /** Короткая подпись темы для кнопок уточнения («Цена за метр»). До 32 символов. */
  label: Localized;
  keywords: ChatKeywords;
  answer: Localized;
  /** Кнопки под ответом, максимум две; порядок сохраняется. */
  actions?: ChatActionKind[];
}

/** Служебные реплики бота. Живут отдельно от тем: по ним не ищут. */
export type ServiceEntryId =
  /** Первое сообщение при открытии виджета. */
  | 'greeting'
  /** Просьба оставить контакты после первого ответа. */
  | 'contacts_request'
  /** Подтверждение после сохранения контактов. */
  | 'contacts_thanks'
  /** Вопрос не распознан. */
  | 'fallback'
  /** Два близких совпадения: бот переспрашивает, а не угадывает. Текст содержит {{a}} и {{b}}. */
  | 'clarify'
  /** Подтверждение, что менеджеру отправлен запрос на звонок. */
  | 'handoff_done';

export type ServiceEntries = Record<ServiceEntryId, ChatEntry>;
